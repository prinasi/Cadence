import { chromium } from "playwright-core";
import assert from "node:assert/strict";
import fs from "node:fs";
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = [];
page.on("console", m => { if (m.type() === "error") errors.push(m.text()); });
page.on("pageerror", e => errors.push(e.message));
await page.goto("http://127.0.0.1:3010", { waitUntil: "networkidle" });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: "networkidle" });
const line = page.locator(".transcript-line").nth(7);
await line.scrollIntoViewIfNeeded();
await line.locator(".time-button, .line-time").first().click();
await page.waitForTimeout(300);
await page.getByRole("button", { name: /Dictate this line/ }).click();
await page.waitForTimeout(400);
await page.getByRole("button", { name: /don’t know/i }).click();
await page.waitForTimeout(500);
await page.locator(".vocab-chip", { hasText: "small" }).click();
await page.waitForTimeout(5500);
const word = (await page.locator(".vocab-word-head h4").textContent()).trim();
const source = (await page.locator(".line-vocab .source-badge").textContent()).trim();
const phrases = await page.locator(".line-vocab .collocation-chip").allTextContents();
const def = (await page.locator(".vocab-senses, .vocab-definition").first().textContent()).trim();
console.log({ word, source, phrases, def: def.slice(0, 180) });
assert.equal(word, "small");
assert.match(source, /Free Dictionary/);
assert.ok(phrases.length >= 2, `phrases: ${phrases}`);
assert.match(def, /Meaning/);
const gloss = (await page.locator(".vocab-translation").textContent()).trim();
assert.match(gloss, /小/);
await page.getByRole("button", { name: /Save word/ }).click();
const stored = await page.evaluate(() => JSON.parse(localStorage.getItem("cadence:items:v1") || "[]"));
assert.equal(stored.length, 1);
assert.equal(stored[0].text, "small");
console.log("stored", {text: stored[0].text, definition: stored[0].definition?.slice(0,60), examples: stored[0].examples?.length, collocations: stored[0].collocations});
fs.mkdirSync("screenshots", { recursive: true });
await page.screenshot({ path: "screenshots/public-dictionary.png" });
assert.deepEqual(errors, []);
console.log("PUBLIC DICTIONARY CHECK PASSED");
await browser.close();
