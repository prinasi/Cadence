import { chromium } from "playwright-core";
import assert from "node:assert/strict";
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
await page.goto("http://127.0.0.1:3010", { waitUntil: "networkidle" });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: "networkidle" });
await page.locator(".transcript-line").nth(1).scrollIntoViewIfNeeded();
await page.evaluate(() => {
  const line = document.querySelectorAll(".transcript-line")[1];
  const tokens = line.querySelectorAll("[data-token-id]");
  const range = document.createRange();
  range.setStartBefore(tokens[1]);
  range.setEndAfter(tokens[2]);
  const selection = window.getSelection();
  selection.removeAllRanges();
  selection.addRange(range);
  line.dispatchEvent(new MouseEvent("mouseup", { bubbles: true }));
});
await page.waitForTimeout(200);
await page.locator(".dictionary-actions .button-ghost").click();
await page.waitForTimeout(300);
await page.getByRole("button", { name: /don’t know/i }).click();
await page.waitForTimeout(400);
const phraseSave = page.getByRole("button", { name: /Save phrase/ });
assert.ok(await phraseSave.isVisible());
await phraseSave.click();
await page.waitForTimeout(300);
const items = await page.evaluate(() => JSON.parse(localStorage.getItem("cadence:items:v1") || "[]"));
assert.equal(items.length, 1);
assert.equal(items[0].type, "phrase");
assert.equal(items[0].text, "real progress");
console.log("PHRASE SAVE OK", items[0]);
await browser.close();
