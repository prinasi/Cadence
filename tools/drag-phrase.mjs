import { chromium } from "playwright-core";
import assert from "node:assert/strict";
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
await page.goto("http://127.0.0.1:3010", { waitUntil: "networkidle" });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: "networkidle" });
const line = page.locator(".transcript-line").nth(1);
await line.scrollIntoViewIfNeeded();
const start = await line.locator(".word-token", { hasText: "real" }).boundingBox();
const end = await line.locator(".word-token", { hasText: "progress" }).boundingBox();
assert.ok(start && end);
await page.mouse.move(start.x + 8, start.y + start.height / 2);
await page.mouse.down();
await page.mouse.move(end.x + end.width - 3, end.y + end.height / 2, { steps: 12 });
await page.mouse.up();
await page.waitForTimeout(400);
const head = await page.locator(".dictionary-headword h2").textContent().catch(() => "");
console.log("selected:", head, "type:", await page.locator(".section-kicker").first().textContent());
await page.screenshot({ path: "screenshots/drag-phrase.png" });
await browser.close();
