import { chromium } from "playwright-core";
import assert from "node:assert/strict";
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1200, height: 900 } });
const errors = [];
page.on("console", m => { if (m.type() === "error") errors.push(m.text()); });
page.on("pageerror", e => errors.push(e.message));
await page.goto("http://127.0.0.1:3011", { waitUntil: "networkidle", timeout: 120000 });
await page.getByRole("button", { name: /Import lesson/ }).click();
await page.locator('input[accept*="video"]').setInputFiles("public/demo/small-habits.mp4");
await page.locator('input[accept*=".srt"]').setInputFiles("public/demo/small-habits.srt");
await page.locator(".title-field input").fill("Dev StrictMode Lesson");
await page.locator(".video-probe.is-ok").waitFor({ timeout: 15000 });
await page.getByRole("button", { name: /Start learning/ }).click();
await page.waitForTimeout(2000);
assert.equal(await page.locator(".lesson-title-copy h1").textContent(), "Dev StrictMode Lesson");
await page.reload({ waitUntil: "networkidle", timeout: 120000 });
await page.waitForTimeout(1500);
console.log("restored title:", await page.locator(".lesson-title-copy h1").textContent());
assert.equal(await page.locator(".lesson-title-copy h1").textContent(), "Dev StrictMode Lesson");
console.log("errors:", errors);
await browser.close();
