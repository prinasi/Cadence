import { chromium } from "playwright-core";
import assert from "node:assert/strict";
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors=[]; page.on('console',m=>{if(m.type()==='error') errors.push(m.text())}); page.on('pageerror',e=>errors.push(e.message));
await page.goto("http://127.0.0.1:3010", { waitUntil: "networkidle" });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: "networkidle" });
await page.locator(".mobile-dock button:nth-child(3)").click();
await page.getByRole("button", { name: "Add", exact: true }).click();
await page.waitForTimeout(300);
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth), 0);
assert.ok(await page.locator(".notebook-add-form").isVisible());
await page.getByLabel("New notebook text").fill("deliberate");
await page.getByLabel("New notebook meaning").fill("故意的");
await page.getByRole("button", { name: /Add to notebook/ }).click();
await page.waitForTimeout(400);
assert.equal(await page.locator(".notebook-item").count(), 1);
console.log("mobile notebook add OK", errors);
assert.deepEqual(errors, []);
await browser.close();
