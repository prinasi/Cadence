import { chromium } from "playwright-core";
import assert from "node:assert/strict";
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors=[]; page.on('console',m=>{if(m.type()==='error') errors.push(m.text())}); page.on('pageerror',e=>errors.push(e.message));
await page.goto("http://127.0.0.1:3010", { waitUntil: "networkidle" });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: "networkidle" });
await page.locator(".mobile-dock button:nth-child(2)").click();
await page.waitForTimeout(300);
await page.getByLabel("Start from line").selectOption("6");
await page.waitForTimeout(250);
assert.equal((await page.locator(".practice-progress-label").textContent()).trim(), "Line 7 / 10");
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth), 0);
assert.ok(await page.getByRole("button", { name: "Skip", exact: true }).isVisible());
await page.screenshot({ path: "screenshots/mobile-start-skip.png" });
await page.getByRole("button", { name: "Skip", exact: true }).click();
await page.waitForTimeout(200);
assert.equal((await page.locator(".practice-progress-label").textContent()).trim(), "Line 8 / 10");
console.log("MOBILE START/SKIP OK", errors);
assert.deepEqual(errors, []);
await browser.close();
