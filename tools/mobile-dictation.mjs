import { chromium } from "playwright-core";
import assert from "node:assert/strict";
import fs from "node:fs";
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
page.on("console", m => { if (m.type() === "error") errors.push(m.text()); });
page.on("pageerror", e => errors.push(e.message));
await page.goto("http://127.0.0.1:3010", { waitUntil: "networkidle" });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: "networkidle" });
await page.locator(".mobile-dock button:nth-child(2)").click();
await page.waitForTimeout(300);
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth), 0);
await page.getByRole("button", { name: /don’t know/i }).click();
await page.waitForTimeout(700);
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth), 0);
assert.ok(await page.locator(".line-vocab").isVisible());
fs.mkdirSync("screenshots", { recursive: true });
await page.screenshot({ path: "screenshots/mobile-dictation-top.png" });
await page.locator(".line-vocab").scrollIntoViewIfNeeded();
await page.waitForTimeout(300);
await page.screenshot({ path: "screenshots/mobile-dictation-vocab.png" });
console.log("mobile dictation overflow/errors", errors);
assert.deepEqual(errors, []);
await browser.close();
