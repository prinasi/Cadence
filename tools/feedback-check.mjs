import { chromium } from "playwright-core";
import assert from "node:assert/strict";
import fs from "node:fs";
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors=[]; page.on('console',m=>{if(m.type()==='error') errors.push(m.text())}); page.on('pageerror',e=>errors.push(e.message));
await page.goto("http://127.0.0.1:3010", { waitUntil: "networkidle" });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: "networkidle" });
await page.locator(".lesson-actions .button-coral").click();
await page.waitForTimeout(300);
await page.locator(".answer-input").fill("Most of us wait for a big moment to change our live");
await page.getByRole("button", { name: /Check answer/ }).click();
await page.waitForTimeout(500);
const correct = (await page.locator(".correct-sentence-block p").textContent()).trim();
assert.equal(correct, "Most of us wait for a big moment to change our lives.");
const extra = await page.locator(".feedback-word.is-extra").allTextContents();
const missing = await page.locator(".missing-word").allTextContents();
console.log({ correct, extra, missing });
assert.ok(extra.includes("live"));
assert.ok(missing.includes("lives"));
assert.ok(await page.getByRole("button", { name: /Try again/ }).isVisible());
assert.ok(await page.getByRole("button", { name: /Next line/ }).isVisible());
fs.mkdirSync("screenshots", { recursive: true });
await page.screenshot({ path: "screenshots/feedback-red.png" });
await page.getByRole("button", { name: /Try again/ }).click();
await page.waitForTimeout(250);
assert.equal(await page.locator(".answer-input").inputValue(), "");
assert.equal(await page.locator(".answer-input").isDisabled(), false);
await page.locator(".answer-input").fill("Most of us wait for a big moment to change our lives");
await page.getByRole("button", { name: /Check answer/ }).click();
await page.waitForTimeout(400);
assert.ok(await page.locator(".correct-sentence-block").isVisible());
assert.match(await page.locator(".feedback-heading strong").textContent(), /That’s it/);
assert.ok(await page.getByRole("button", { name: /Type again/ }).isVisible());
await page.getByRole("button", { name: /Next line/ }).click();
await page.waitForTimeout(300);
assert.equal((await page.locator(".practice-progress-label").textContent()).trim(), "Line 2 / 10");
console.log("RED DIFF + RETRY + NEXT PASSED", errors);
assert.deepEqual(errors, []);
await browser.close();
