import { chromium } from "playwright-core";
import assert from "node:assert/strict";
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors=[]; page.on('console',m=>{if(m.type()==='error') errors.push(m.text())}); page.on('pageerror',e=>errors.push(e.message));
await page.goto("http://127.0.0.1:3010", { waitUntil: "networkidle" });
await page.getByRole("button", { name: /Import lesson/ }).click();
await page.locator('input[accept*="video"]').setInputFiles("public/demo/small-habits.mp4");
await page.locator('input[accept*=".srt"]').setInputFiles(".tmp/joined.srt");
await page.locator(".video-probe.is-ok").waitFor({ timeout: 15000 });
assert.match(await page.locator(".subtitle-preview").textContent(), /4 cues detected/);
await page.getByRole("button", { name: /Start learning/ }).click();
await page.waitForTimeout(1000);
await page.locator(".lesson-actions .button-coral").click();
await page.waitForTimeout(300);
assert.equal((await page.locator(".practice-progress-label").textContent()).trim(), "Line 1 / 2");
await page.getByRole("button", { name: /don’t know/i }).click();
await page.waitForTimeout(300);
const first = (await page.locator(".correct-sentence-block p").textContent()).trim();
console.log("first line:", first);
assert.equal(first, "Most of us wait for a big moment to change our lives.");
await page.getByRole("button", { name: /Next line/ }).click();
await page.waitForTimeout(200);
await page.getByRole("button", { name: /don’t know/i }).click();
await page.waitForTimeout(200);
const second = (await page.locator(".correct-sentence-block p").textContent()).trim();
console.log("second line:", second);
assert.equal(second, "But real progress rarely arrives in a single leap.");
assert.deepEqual(errors, []);
console.log("CROSS-CUE SEGMENTATION PASSED");
await browser.close();
